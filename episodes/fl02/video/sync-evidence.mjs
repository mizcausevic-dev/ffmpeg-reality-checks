// Usage: node episodes/fl02/video/sync-evidence.mjs [path/to/evidence.json]   (default: out/fl02/evidence.json; run fixture/run.mjs first)
// Rewrites the block between the EVIDENCE markers in fl02/video/Scenes.tsx and fs02/video/Scenes.tsx from the evidence.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {pickEvidence} from './evidence-pick.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..', '..');
export const START = '/* EVIDENCE:start (generated by fl02/video/sync-evidence.mjs from out/fl02/evidence.json: do not edit by hand) */';
export const END = '/* EVIDENCE:end */';
export const blockOf = (ev) => `${START}\nconst E = ${JSON.stringify(pickEvidence(ev))} as const;\n${END}`;
export function sync(file, ev) {
  const src = fs.readFileSync(file, 'utf8');
  const re = /\/\* EVIDENCE:start[\s\S]*?\/\* EVIDENCE:end \*\//;
  if (!re.test(src)) throw new Error(`${file} has no EVIDENCE block`);
  fs.writeFileSync(file, src.replace(re, () => blockOf(ev)));
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const ev = JSON.parse(fs.readFileSync(process.argv[2] ?? path.join(root, 'out', 'fl02', 'evidence.json'), 'utf8'));
  for (const id of ['fl02', 'fs02']) { const f = path.join(root, 'episodes', id, 'video', 'Scenes.tsx'); if (fs.existsSync(f)) { sync(f, ev); console.log('synced', f); } }
}
