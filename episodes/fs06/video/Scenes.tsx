/** A grid of small squares, `lit` of them filled in the given color, the rest an empty outline. */
const Grid: React.FC<{y: number; cols: number; rows: number; lit: number; color: string; off?: string; o?: number}> = ({y, cols, rows, lit, color, off, o = 1}) => {
  const cell = 50, gap = 5;
  return (
    <div style={{position: 'absolute', left: X0, top: y, width: 880, height: rows * (cell + gap), opacity: o}}>
      {Array.from({length: cols * rows}, (_, k) => {
        const on = k < lit;
        const c = on ? color : off ?? C.line;
        return <div key={k} style={{position: 'absolute', left: (k % cols) * (cell + gap), top: Math.floor(k / cols) * (cell + gap), width: cell, height: cell, boxSizing: 'border-box', border: `3px solid ${c}`, background: on ? `${color}44` : C.bg2, borderRadius: 6}} />;
      })}
    </div>
  );
};

/** One bar split by filter type: `parts` are [count, color, label]; widths are proportional to row counts, with a 6 px floor so one row stays visible. */
const FilterBar: React.FC<{y: number; title: string; titleColor: string; parts: [number, string, string][]; p?: number; o?: number}> = ({y, title, titleColor, parts, p = 1, o = 1}) => {
  const total = parts.reduce((a, q) => a + q[0], 0);
  const floor = 8, free = 874 - floor * parts.length;
  let x = 0;
  return (
    <div style={{position: 'absolute', left: X0, top: y, width: 880, opacity: o}}>
      <div style={{fontFamily: F.sans, fontSize: 32, fontWeight: 700, color: titleColor, whiteSpace: 'nowrap'}}>{title}</div>
      <div style={{position: 'absolute', left: 0, top: 52, width: 880, height: 90, border: `3px solid ${C.line}`, borderRadius: 10, boxSizing: 'border-box', background: C.bg2}}>
        {parts.map(([n, c], i) => {
          const w = (floor + (n / total) * free) * p;
          const left = x; x += w;
          return <div key={i} style={{position: 'absolute', left, top: 0, width: w, height: 84, background: c}} />;
        })}
      </div>
      <div style={{position: 'absolute', left: 0, top: 152, width: 880, fontFamily: F.mono, fontSize: 30, color: C.text, whiteSpace: 'nowrap', opacity: p > 0.8 ? 1 : 0}}>
        {parts.map(([n, c, label], i) => <span key={i} style={{marginRight: 26}}><span style={{color: c}}>{'■'}</span> {label}</span>)}
      </div>
    </div>
  );
};

