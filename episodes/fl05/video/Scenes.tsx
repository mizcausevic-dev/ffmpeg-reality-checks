/** Command block. Lines are drawn as given; `hi` substrings are highlighted. */
const Term: React.FC<{x: number; y: number; w: number; lines: string[]; hi?: string[]; size?: number; color?: string; o?: number}> = ({x, y, w, lines, hi = [], size = 32, color = C.cyan, o = 1}) => {
  const part = (s: string) => {
    if (!hi.length) return s;
    const re = new RegExp(`(${hi.map((h) => h.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})`);
    return s.split(re).map((p, i) => (hi.includes(p) ? <span key={i} style={{color: C.red, fontWeight: 700, background: `${C.red}1f`}}>{p}</span> : p));
  };
  return (
    <div style={{position: 'absolute', left: x, top: y, width: w, boxSizing: 'border-box', opacity: o, background: C.codeBg, border: `3px solid ${color}`, boxShadow: `6px 6px 0 ${color}44`, padding: '20px 26px', fontFamily: F.mono, fontSize: size, lineHeight: 1.45, color: C.text, whiteSpace: 'pre'}}>
      {lines.map((l, i) => <div key={i}>{i === 0 ? <span style={{color}}>$ </span> : '  '}{part(l)}</div>)}
    </div>
  );
};

