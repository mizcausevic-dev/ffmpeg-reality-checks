/** A chroma diagram: 4x4 pixels (grey luma tiles). 444 puts a colour sample on every pixel, 420 one on every 2x2 block. */
const ChromaGrid: React.FC<{x: number; y: number; cell?: number; mode: '444' | '420'; color?: string; o?: number; p?: number}> = ({x, y, cell = 78, mode, color = C.red, o = 1, p = 1}) => {
  const tiles = [];
  for (let r = 0; r < 4; r++) for (let c = 0; c < 4; c++) tiles.push(<div key={`t${r}${c}`} style={{position: 'absolute', left: c * cell, top: r * cell, width: cell - 6, height: cell - 6, background: C.panel, border: `2px solid ${C.line}`}} />);
  const dots = [];
  if (mode === '444') {
    for (let r = 0; r < 4; r++) for (let c = 0; c < 4; c++) dots.push(<div key={`d${r}${c}`} style={{position: 'absolute', left: c * cell + (cell - 6) / 2 - 11, top: r * cell + (cell - 6) / 2 - 11, width: 22, height: 22, borderRadius: '50%', background: color, opacity: ep(p, 0, 1)}} />);
  } else {
    for (let r = 0; r < 2; r++) for (let c = 0; c < 2; c++) {
      dots.push(<div key={`b${r}${c}`} style={{position: 'absolute', left: c * 2 * cell - 4, top: r * 2 * cell - 4, width: 2 * cell - 6 + 8, height: 2 * cell - 6 + 8, border: `4px solid ${color}`, boxSizing: 'border-box'}} />);
      dots.push(<div key={`e${r}${c}`} style={{position: 'absolute', left: c * 2 * cell + cell - 3 - 19, top: r * 2 * cell + cell - 3 - 19, width: 38, height: 38, borderRadius: '50%', background: color}} />);
    }
  }
  return <div style={{position: 'absolute', left: x, top: y, width: cell * 4, height: cell * 4, opacity: o}}>{tiles}{dots}</div>;
};

type Box = {type: string; offset: number; size: number};
/** The top-level boxes of an MP4 as one bar, drawn to scale with the file's bytes. The moov box (the index) takes `moovColor`. */
const BoxMap: React.FC<{x: number; y: number; w: number; h?: number; boxes: readonly Box[]; moovColor: string; label: string; o?: number; p?: number}> = ({x, y, w, h = 64, boxes, moovColor, label, o = 1, p = 1}) => {
  const total = boxes.reduce((a, b) => a + b.size, 0);
  const iw = w - 6; // inside the 3 px border
  const rect = (b: Box) => ({left: (b.offset / total) * iw, width: Math.max(6, (b.size / total) * iw)});
  const moov = boxes.find((b) => b.type === 'moov')!;
  const mdat = boxes.find((b) => b.type === 'mdat')!;
  const moovFirst = moov.offset < mdat.offset;
  const mr = rect(moov), dr = rect(mdat);
  const lab = `moov, the index: bytes ${fmt(moov.offset)} to ${fmt(moov.offset + moov.size)}`;
  return (
    <div style={{position: 'absolute', left: x, top: y, width: w, height: h + 120, opacity: o}}>
      <T x={0} y={0} size={24} weight={700} ls={1} color={C.dim}>{label}</T>
      <T x={0} y={0} w={w} size={24} role="mono" weight={400} color={C.mute} align="right">{`${fmt(total)} bytes`}</T>
      <div style={{position: 'absolute', left: 0, top: 38, width: w, height: h, background: C.bg2, border: `3px solid ${C.text}`, boxSizing: 'border-box'}}>
        {boxes.map((b) => {
          const r = rect(b);
          const col = b.type === 'moov' ? moovColor : b.type === 'mdat' ? C.cyanDim : C.mute;
          return <div key={b.type} style={{position: 'absolute', left: r.left, top: 0, width: r.width * ep(p, 0, 1), height: h - 6, background: col, boxSizing: 'border-box'}} />;
        })}
        <T x={dr.left} y={(h - 6) / 2 - 20} w={dr.width} size={32} role="mono" align="center" color={C.text} o={ep(p, 0.4, 1)}>mdat: the picture and the sound</T>
      </div>
      <div style={{position: 'absolute', left: 0, top: 38 + h + 4, width: w, opacity: ep(p, 0.5, 1)}}>
        <div style={{position: 'absolute', left: 3 + mr.left + mr.width / 2 - 2, top: 0, width: 4, height: 30, background: moovColor}} />
        <T x={moovFirst ? 3 + mr.left : 3 + mr.left + mr.width - 900} y={34} w={900} size={30} role="mono" color={moovColor} align={moovFirst ? 'left' : 'right'}>{lab}</T>
      </div>
    </div>
  );
};

