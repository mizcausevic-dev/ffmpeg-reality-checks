// Usage: node episodes/fl05/fixture/gen-scene-data.mjs [evidence.json]
// Runs the fl05 experiment (or reads an evidence.json) and rewrites the DATA block in fl05 and fs05 Scenes.tsx.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
import {runExperiment} from './experiment.mjs';
import {sceneData} from './scene-data.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const ev = process.argv[2] ? JSON.parse(fs.readFileSync(process.argv[2], 'utf8')) : await runExperiment(fs.mkdtempSync(path.join(os.tmpdir(), 'frc-fl05-scene-')));
const block = `// DATA-BEGIN (generated by episodes/fl05/fixture/gen-scene-data.mjs; a test keeps it equal to the evidence)\nconst DATA = ${JSON.stringify(sceneData(ev), null, 1)} as const;\n// DATA-END`;
for (const f of [path.join(here, '..', 'video', 'Scenes.tsx'), path.join(here, '..', '..', 'fs05', 'video', 'Scenes.tsx')]) {
  if (!fs.existsSync(f)) continue;
  const src = fs.readFileSync(f, 'utf8');
  const re = /\/\/ DATA-BEGIN[\s\S]*?\/\/ DATA-END/;
  if (!re.test(src)) throw new Error(`${f} has no DATA block`);
  fs.writeFileSync(f, src.replace(re, () => block));
  console.log('updated', f);
}
