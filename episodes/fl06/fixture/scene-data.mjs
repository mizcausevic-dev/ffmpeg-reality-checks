// The numbers the fl06 and fs06 scenes draw. Built from the two SAVED evidence files (ffmpeg 6.1.1 and ffmpeg 8.1.2), so a
// scene never holds a number that is not in the evidence. gen-scene-data.mjs writes this object into the DATA block of
// both Scenes.tsx files; a test keeps the block equal to what this function returns.
import fs from 'node:fs';
import path from 'node:path';
import {compareEvidence, PREDS} from './experiment.mjs';

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
export const loadSaved = () => ({
  a: JSON.parse(fs.readFileSync(path.join(here, '..', 'evidence-6.1.1.json'), 'utf8')),
  b: JSON.parse(fs.readFileSync(path.join(here, '..', 'evidence-8.1.2.json'), 'utf8')),
});
const r1 = (x) => Math.round(x * 10) / 10;
export const pct = (from, to) => r1((to / from - 1) * 100);

export function sceneData({a, b} = loadSaved()) {
  const cmp = compareEvidence(a, b);
  const sizes = {};
  for (const name of Object.keys(a.contents)) {
    const ca = a.contents[name], cb = b.contents[name];
    const pick = (c) => Object.fromEntries(['default', ...PREDS].map((k) => [k, c.runs[k].bytes]));
    sizes[name] = {
      what: ca.what, pix: ca.pix, width: ca.width, height: ca.height,
      a: pick(ca), b: pick(cb),
      histA: ca.runs.default.reader2.histogram, histB: cb.runs.default.reader2.histogram,
      mixedHistA: ca.runs.mixed.reader2.histogram, mixedHistB: cb.runs.mixed.reader2.histogram,
      md5: ca.runs.default.reader1.decodedMd5.slice(0, 8),
      pctDefault: pct(ca.runs.default.bytes, cb.runs.default.bytes),
    };
  }
  const t = (x, k) => x.contents.testsrc2.runs[k].sha256.slice(0, 8);
  const lv = (x) => Object.fromEntries(Object.entries(x.levels).map(([n, l]) => [n, Object.fromEntries(Object.entries(l).map(([k, r]) => [k, r.bytes]))]));
  return {
    builds: {
      a: {v: '6.1.1', name: 'Ubuntu build', libavcodec: a.libs.find((l) => /^libavcodec/.test(l)).replace(/ \/.*/, '').replace('libavcodec ', '').replace(/\s/g, '')},
      b: {v: '8.1.2', name: 'Windows full build', libavcodec: b.libs.find((l) => /^libavcodec/.test(l)).replace(/ \/.*/, '').replace('libavcodec ', '').replace(/\s/g, '')},
    },
    help: {a: {line: a.help.predLine.replace(/\s+/g, ' '), def: a.help.predDefault}, b: {line: b.help.predLine.replace(/\s+/g, ' '), def: b.help.predDefault}},
    control: Object.fromEntries(Object.entries(a.control).map(([k, c]) => [k, {histogram: c.histogram, firstRows: c.parsedRows}])),
    sizes,
    sha: {testsrc2: {aDefault: t(a, 'default'), bDefault: t(b, 'default'), aPaeth: t(a, 'paeth'), bPaeth: t(b, 'paeth')}},
    firstRows: {a: a.contents.testsrc2.runs.default.reader2.firstRows, b: b.contents.testsrc2.runs.default.reader2.firstRows, paethA: a.contents.testsrc2.runs.paeth.reader2.firstRows},
    levels: {a: lv(a), b: lv(b)},
    cross: {
      files: cmp.rows.length, images: Object.keys(a.contents).length,
      allPixelsSame: cmp.allPixelsSame,
      explicitTotal: cmp.explicitTotal, explicitSameBytes: cmp.explicitSameBytes, explicitSameHistogram: cmp.explicitSameHistogram,
      defaultTotal: cmp.defaultTotal, defaultSameBytes: cmp.defaultSameBytes,
      repeats: a.repeats,
    },
  };
}

export const dataBlock = (d) => `// DATA-BEGIN (generated by episodes/fl06/fixture/gen-scene-data.mjs from evidence-6.1.1.json and evidence-8.1.2.json; a test keeps it equal)\nconst DATA = ${JSON.stringify(d, null, 1)} as const;\n// DATA-END`;
export const dataRe = /\/\/ DATA-BEGIN[\s\S]*?\/\/ DATA-END/;
