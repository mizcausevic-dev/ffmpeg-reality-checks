// The numbers the scenes draw and the scripts speak. Derived from the two evidence files (6.1.1 = a, 8.1.2 = b), never typed by hand:
// `node episodes/fl07/fixture/gen-facts.mjs` rewrites the `E` block (between the E:start and E:end markers) of fl07/video/Scenes.tsx
// and fs07/video/Scenes.tsx. The tests re-derive the block from the evidence files and fail if a Scenes.tsx has drifted.
const r = (n, d) => Math.round(n * 10 ** d) / 10 ** d;
const pct = (x, y) => Math.round((x / y - 1) * 100); // x is this many percent bigger than y
const kb = (n) => Math.round(n / 1000);
const errOf = (c) => ((/Value 64\.000000 for parameter 'crf' out of range \[[^\]]+\]/.exec(c.error) ?? [''])[0]);
function build(ev) {
  const all = {...ev.cases, ...ev.long};
  const m = (k) => {
    const c = all[k];
    if (!c) throw new Error(`no case ${k}`);
    if (c.failed) return {failed: true, error: String(c.error).replace(/\s+/g, ' ')};
    return {failed: false, md5: c.packetMd5.slice(0, 8), bytes: c.fileBytes, kb: kb(c.fileBytes), ssim: r(c.ffmpegSsimAll, 4), psnr: c.ffmpegPsnrAvg === null ? null : r(c.ffmpegPsnrAvg, 2), lossless: c.lossless, key: c.keyframes, keySeconds: c.keyframeSeconds, rf: c.svt ? c.svt.rateFactor : null, gop: c.svt ? c.svt.gop : null, seek: c.seek ?? null};
  };
  const ver = /version (\d+\.\d+(?:\.\d+)?)/.exec(ev.ffmpeg)[1];
  const svtMajor = /^(\d+\.\d+)/.exec(ev.libs.svtav1)[1];
  const aomVer = ev.libs.aom ? ev.libs.aom.replace(/^v/, '') : null;
  const bvSvt = m('svt_clean_p8_crf30_b500k');
  return {
    ffmpeg: ver, svt: svtMajor, aom: aomVer,
    clean: {svt30: m('svt_clean_p8_crf30'), aom30: m('aom_clean_u8_crf30'), svt0: m('svt_clean_p8_crf0'), svtNo: m('svt_clean_p8_nocrf'), aom0: m('aom_clean_u8_crf0'), svt63: m('svt_clean_p8_crf63'),
      p4: m('svt_clean_p4_crf30'), p8: m('svt_clean_p8_crf30'), p12: m('svt_clean_p12_crf30'), aomBv: m('aom_clean_u8_crf30_b500k')},
    noisy: {svt30: m('svt_noisy_p8_crf30'), aom30: m('aom_noisy_u8_crf30'), p8: m('svt_noisy_p8_crf30'), p12: m('svt_noisy_p12_crf30'), aomBv: m('aom_noisy_u8_crf30_b500k')},
    svtBv: bvSvt.failed ? {failed: true, msg: (/Target Bitrate only supported when --rc is \d\/\d \(VBR\/CBR\)\. Current --rc: \d/.exec(bvSvt.error) ?? [bvSvt.error])[0]} : {failed: false, bytes: bvSvt.bytes, same: all.svt_clean_p8_crf30.packetMd5 === all.svt_clean_p8_crf30_b500k.packetMd5},
    b0: {aom: all.aom_clean_u8_crf30.packetMd5 === all.aom_clean_u8_crf30_b0.packetMd5, svt: all.svt_clean_p8_crf30.packetMd5 === all.svt_clean_p8_crf30_b0.packetMd5,
      aomMd5: [all.aom_clean_u8_crf30.packetMd5.slice(0, 8), all.aom_clean_u8_crf30_b0.packetMd5.slice(0, 8)], svtMd5: [all.svt_clean_p8_crf30.packetMd5.slice(0, 8), all.svt_clean_p8_crf30_b0.packetMd5.slice(0, 8)]},
    err64: {svt: errOf(all.svt_clean_p8_crf64), aom: errOf(all.aom_clean_u8_crf64)},
    zeroSame: all.svt_clean_p8_crf0.packetMd5 === all.svt_clean_p8_nocrf.packetMd5,
    aomLossless: all.aom_clean_u8_crf0.packetMd5 === all.aom_clean_u8_lossless.packetMd5,
    long: {svtDef: m('svt_long_default'), aomDef: m('aom_long_default'), svtG25: m('svt_long_g25'), aomG25: m('aom_long_g25')},
    d: { // derived
      aomZeroTimes: r(all.aom_clean_u8_crf0.fileBytes / all.aom_clean_u8_crf30.fileBytes, 1),
      p12Pct: pct(all.svt_clean_p12_crf30.fileBytes, all.svt_clean_p8_crf30.fileBytes),
      scalePct: pct(all.svt_clean_p8_crf30.fileBytes, all.aom_clean_u8_crf30.fileBytes),
      g25AomPct: pct(all.aom_long_g25.fileBytes, all.aom_long_default.fileBytes),
      g25SvtPct: pct(all.svt_long_g25.fileBytes, all.svt_long_default.fileBytes),
      aomBvNoisyPct: pct(all.aom_noisy_u8_crf30_b500k.fileBytes, all.aom_noisy_u8_crf30.fileBytes),
    },
  };
}
export function sceneFacts(a, b) {
  return {
    a: build(a), b: build(b),
    p: {crf: [0, 30, 63, 64], preset: [4, 8, 12], bitrateK: 500, g: [25, 100], seekFrame: 300, seekSeconds: 12, frames: 400, fps: 25, clipSeconds: 16, shortFrames: 50, keyCount25: 16},
  };
}
export const factsBlock = (facts) => `// E:start (generated by episodes/fl07/fixture/gen-facts.mjs from evidence-6.1.1.json and evidence-8.1.2.json; do not edit by hand)\nconst E: any = ${JSON.stringify(facts, null, 1).replace(/\n\s*/g, ' ')};\n// E:end`;
export const blockRe = /\/\/ E:start[\s\S]*?\/\/ E:end/;
