/** 4x4 pixels as grey tiles. 444 puts a colour sample on every pixel, 420 one on every 2x2 block. */
const Chroma: React.FC<{x: number; y: number; cell: number; mode: '444' | '420'; color?: string; o?: number}> = ({x, y, cell, mode, color = C.red, o = 1}) => {
  const els: React.ReactNode[] = [];
  const tile = cell - 6;
  for (let r = 0; r < 4; r++) for (let c = 0; c < 4; c++) els.push(<div key={`t${r}${c}`} style={{position: 'absolute', left: c * cell, top: r * cell, width: tile, height: tile, background: C.panel, border: `2px solid ${C.line}`}} />);
  if (mode === '444') {
    const d = Math.round(cell * 0.28);
    for (let r = 0; r < 4; r++) for (let c = 0; c < 4; c++) els.push(<div key={`d${r}${c}`} style={{position: 'absolute', left: c * cell + tile / 2 - d / 2, top: r * cell + tile / 2 - d / 2, width: d, height: d, borderRadius: '50%', background: color}} />);
  } else {
    const d = Math.round(cell * 0.5);
    for (let r = 0; r < 2; r++) for (let c = 0; c < 2; c++) {
      els.push(<div key={`b${r}${c}`} style={{position: 'absolute', left: c * 2 * cell - 4, top: r * 2 * cell - 4, width: 2 * tile + 14, height: 2 * tile + 14, border: `4px solid ${color}`, boxSizing: 'border-box'}} />);
      els.push(<div key={`e${r}${c}`} style={{position: 'absolute', left: c * 2 * cell + cell - 3 - d / 2, top: r * 2 * cell + cell - 3 - d / 2, width: d, height: d, borderRadius: '50%', background: color}} />);
    }
  }
  return <div style={{position: 'absolute', left: x, top: y, width: cell * 4, height: cell * 4, opacity: o}}>{els}</div>;
};

