/** One MP4 as a bar drawn to scale with its bytes. The moov box (the index) takes `moovColor`. */
const BoxBar: React.FC<{y: number; boxes: readonly Box[]; moovColor: string; title: string; o?: number; p?: number}> = ({y, boxes, moovColor, title, o = 1, p = 1}) => {
  const total = boxes.reduce((a, b) => a + b.size, 0);
  const iw = W - 6;
  const rect = (b: Box) => ({left: (b.offset / total) * iw, width: Math.max(6, (b.size / total) * iw)});
  const moov = boxes.find((b) => b.type === 'moov')!;
  const mdat = boxes.find((b) => b.type === 'mdat')!;
  const first = moov.offset < mdat.offset;
  const mr = rect(moov), dr = rect(mdat);
  return (
    <div style={{position: 'absolute', left: X0, top: y, width: W, height: 230, opacity: o}}>
      <VT x={0} y={0} size={32} weight={700} color={C.text}>{title}</VT>
      <div style={{position: 'absolute', left: 0, top: 50, width: W, height: 80, background: C.bg2, border: `3px solid ${C.text}`, boxSizing: 'border-box'}}>
        {boxes.map((b) => {
          const r = rect(b);
          return <div key={b.type} style={{position: 'absolute', left: r.left, top: 0, width: r.width * ep(p, 0, 1), height: 74, background: b.type === 'moov' ? moovColor : b.type === 'mdat' ? C.cyanDim : C.mute}} />;
        })}
        <VT x={dr.left} y={20} w={dr.width} size={30} role="mono" align="center" o={ep(p, 0.4, 1)}>mdat: picture and sound</VT>
      </div>
      <div style={{position: 'absolute', left: 3 + mr.left + mr.width / 2 - 2, top: 134, width: 4, height: 32, background: moovColor, opacity: ep(p, 0.5, 1)}} />
      <VT x={0} y={170} size={28} role="mono" color={moovColor} align={first ? 'left' : 'right'} o={ep(p, 0.5, 1)}>{`moov, the index: bytes ${fmt(moov.offset)} to ${fmt(moov.offset + moov.size)}`}</VT>
    </div>
  );
};

